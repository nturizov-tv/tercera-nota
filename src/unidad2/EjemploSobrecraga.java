package unidad2;

public class EjemploSobrecraga {
    // Sumar dos enteros
    public int sumar(int a, int b) {
        return a + b;
    }

    // Sumar tres enteros
    public int sumar(int a, int b, int c) {
        return a + b + c;
    }

    // Sumar dos números de tipo double
    public double sumar(double a, double b) {
        return a + b;
    }
}